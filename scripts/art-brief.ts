/**
 * Writes ART.md: the step-by-step brief for painting every scene in ChatGPT,
 * generated from the content files so it never drifts from the site.
 *   npm run art:brief
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { HOUSE_STYLE, INBOX, SIZE, layerPrompt, loadScenes, masterPrompt, readManifest, MANIFEST, LOCAL_MANIFEST } from './lib/art';

const scenes = loadScenes();
const published = { ...readManifest(MANIFEST), ...readManifest(LOCAL_MANIFEST) };

const have = (key: string, id: string) => existsSync(join(INBOX, key, `${id}.png`));
const status = (key: string, revision: number, ids: string[]) => {
  const p = published[key];
  if (p && p.revision === revision) return `✅ published (r${revision}: ${p.layers.join(', ')})`;
  const inbox = ids.filter((id) => have(key, id));
  return inbox.length ? `🟡 in art/ (${inbox.join(', ')}) — run \`npm run art:process\`` : '⬜ not painted yet';
};

const fence = (text: string) => `\`\`\`text\n${text}\n\`\`\``;

const sections = scenes.map((s, i) => {
  const ids = ['full', ...s.layers.map((l) => l.id)];
  const steps = [
    `**Step 1 — paint the whole picture.** New ChatGPT image chat, paste:\n\n${fence(masterPrompt(s))}\n\nSave the result as \`art/${s.key}/full.png\`.`,
    ...s.layers.map(
      (l, j) =>
        `**Step ${j + 2} — ${l.id}${l.transparent ? ' (transparent cut-out)' : ' (backdrop)'}.** In the same chat, attach \`full.png\` again and paste:\n\n${fence(layerPrompt(s, l))}\n\nSave as \`art/${s.key}/${l.id}.png\`.`,
    ),
  ];
  return [
    `## ${i + 1}. ${s.title}`,
    `Folder \`art/${s.key}/\` · ${SIZE[s.format].label} · revision ${s.revision} · ${status(s.key, s.revision, ids)}`,
    `_${s.alt}_`,
    ...steps,
  ].join('\n\n');
});

const inboxExtras = existsSync(INBOX)
  ? readdirSync(INBOX).filter((d) => !scenes.some((s) => s.key === d))
  : [];

const md = `# Art brief

_Generated by \`npm run art:brief\` from \`/content\`. Do not edit by hand: change a scene's \`prompt\`, \`layers\` or \`revision\` in its content file and re-run._

The Edition is a run of full-screen painted scenes. Each scene is **one painting cut into layers**: a backdrop, then transparent cut-outs of the figures and of the nearest objects. The site moves the layers at different speeds as you scroll, which gives the 3D depth. A scene with only \`full.png\` still works, with a slow camera push and no depth.

## How to paint a scene in ChatGPT

1. Open a **new image chat** for each scene, so earlier scenes don't bleed in.
2. **Step 1:** paste the master prompt. Regenerate until you love it. Composition matters more than detail: you want a clear backdrop, a middle ground, and something close to the viewer along the edges.
3. **Steps 2–4:** attach that same image and paste each layer prompt. Check that each cut-out lines up with the original. If it drifts, ask ChatGPT to *"keep the exact position and scale of the original"* and try again. Small drift is fine; it moves anyway.
4. Download each image as **PNG** with the file name shown, into \`art/<folder>/\`. Cut-outs must keep their transparency.
5. Then either:
   - **Send the PNGs to me in chat** and I'll process them and preview the site, or
   - run \`npm run art:process\` to preview locally, then upload: drag the \`art/<folder>/\` folders into \`gs://ntsikagqiba-assets/originals/\` in the Cloud Console and run the **Art** workflow, or run \`npm run art:process -- --upload\` from your machine.

To repaint a scene later, bump its \`revision\`, paint again and process again. Never overwrite a published revision's files with different art: they are cached for a year.

**Suggested order:** the Frontispiece first, since it's the first impression and the share image, then Chatly to prove the cut-out workflow end to end, then the remaining chapters, the Finale, and the four craft tondi last (one image each, no layers).

**House style** (already included in every master prompt):

> ${HOUSE_STYLE}

${sections.join('\n\n---\n\n')}
${inboxExtras.length ? `\n---\n\n⚠️ Folders in \`art/\` that match no scene: ${inboxExtras.map((d) => `\`${d}\``).join(', ')}\n` : ''}`;

writeFileSync('ART.md', md);
console.log(`ART.md: ${scenes.length} scenes, ${scenes.reduce((n, s) => n + 1 + s.layers.length, 0)} images to paint.`);
